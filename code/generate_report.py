"""
Generate per-model REPORT.md from all the JSON outputs.

Usage:
    python generate_report.py --model qwen2.5-7b-instruct
"""

import argparse
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS_ROOT = REPO_ROOT / "results"


def load(p):
    if not p.exists():
        return None
    with open(p) as f:
        return json.load(f)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, help="model slug")
    args = ap.parse_args()

    model_dir = RESULTS_ROOT / args.model
    val = load(model_dir / "validation_results.json")
    probe = load(model_dir / "probe_results.json")
    arousal = load(model_dir / "arousal_results.json")
    implicit = load(model_dir / "implicit_emotion_results.json")
    pca_info = load(model_dir / "pca_info.json")

    if val is None:
        print(f"No validation_results.json found for {args.model}; skipping report")
        return

    layers = sorted([k for k in val.keys() if k.startswith("layer_")])

    lines = [f"# {args.model} — emotion-vector-bench report\n"]
    lines.append(f"Auto-generated by `code/generate_report.py`. Source data: this directory.\n")

    # Validation summary
    lines.append("## 1. Geometry validation\n")
    lines.append(f"| Layer | Within-cosine | Cross-cosine | Diff | Diff > 0 | PC1 valence sep |")
    lines.append(f"|---|---|---|---|---|---|")
    for lk in layers:
        c = val[lk]["cosine"]
        p = val[lk]["pca"]
        diff = c.get("diff", c.get("within_minus_cross", c["within_cluster_mean"] - c["cross_cluster_mean"]))
        passed_cos = "✓" if c.get("passed", False) else "✗"
        lines.append(f"| {lk} | {c['within_cluster_mean']:.3f} | {c['cross_cluster_mean']:.3f} | {diff:.3f} | {passed_cos} | {p['valence_separation_pc1']:.2f} |")
    xl = val.get("cross_layer_stability", {}).get("mean_correlation", "?")
    if isinstance(xl, (int, float)):
        lines.append(f"\n**Cross-layer stability:** {xl:.3f} (correlation of cosine matrices across layers)\n")

    # Probe accuracy + bootstrap + permutation
    if probe:
        lines.append("\n## 2. Probe accuracy, bootstrap CIs, and permutation tests\n")
        lines.append(f"Linear probe (logistic regression, 5-fold CV) trained on activations to predict emotion (1 of {probe['n_emotions']}).")
        lines.append(f"Chance accuracy: {probe['chance']:.3f}\n")
        lines.append(f"| Layer | Probe acc | × chance | Diff CI | Permutation p |")
        lines.append(f"|---|---|---|---|---|")
        for lk in sorted(probe["layers"].keys()):
            ld = probe["layers"][lk]
            ci = ld["bootstrap"]
            perm = ld["permutation"]
            lines.append(f"| {lk} | {ld['probe_accuracy_mean']:.3f} ± {ld['probe_accuracy_std']:.3f} | "
                         f"{ld['probe_accuracy_factor_over_chance']:.1f}x | "
                         f"[{ci['diff_ci_low']:.3f}, {ci['diff_ci_high']:.3f}] | "
                         f"{perm['p_value']:.3f} |")
        lines.append("")

    # Arousal axis recovery
    if arousal:
        lines.append("## 3. Affective circumplex (valence × arousal)\n")
        lines.append(f"| Layer | Valence on | Sep | Arousal on | Sep |")
        lines.append(f"|---|---|---|---|---|")
        for lk in sorted(arousal["layers"].keys()):
            ld = arousal["layers"][lk]
            lines.append(f"| {lk} | PC{ld['best_valence_pc']} | {ld['valence_separation']:.2f} | PC{ld['best_arousal_pc']} | {ld['arousal_separation']:.2f} |")
        lines.append("")

    # Implicit emotion test
    if implicit:
        lines.append("## 4. Implicit-emotion scenarios\n")
        lines.append(f"Tested on {implicit['n_scenarios']} scenarios that evoke specific emotions without naming them.")
        lines.append(f"At layer {implicit['layer']}.\n")
        lines.append(f"| Metric | Value | Chance |")
        lines.append(f"|---|---|---|")
        n = implicit["n_scenarios"]
        lines.append(f"| Top-1 accuracy | {implicit['top1_accuracy']:.0%} | 5% |")
        lines.append(f"| Top-3 accuracy | {implicit['top3_accuracy']:.0%} | 15% |")
        lines.append(f"| Top-5 accuracy | {implicit['top5_accuracy']:.0%} | 25% |")
        lines.append("")
        lines.append("Per-scenario breakdown:")
        lines.append(f"| Target emotion | Rank | Top 3 predictions |")
        lines.append(f"|---|---|---|")
        for sc in implicit["scenarios"]:
            top3 = ", ".join(sc["top5_emotions"][:3])
            lines.append(f"| {sc['target']} | #{sc['target_rank']} | {top3} |")

    # Plots index
    lines.append("\n## 5. Plots\n")
    lines.append("Generated plots in `plots/`:")
    plots_dir = model_dir / "plots"
    if plots_dir.exists():
        for plot in sorted(plots_dir.iterdir()):
            lines.append(f"- {plot.name}")

    # Summary
    lines.append("\n## 6. Summary judgment\n")
    if probe and probe["layers"]:
        best_layer = max(probe["layers"].keys(), key=lambda lk: probe["layers"][lk]["probe_accuracy_mean"])
        best_acc = probe["layers"][best_layer]["probe_accuracy_mean"]
        lines.append(f"- **Best probe layer**: {best_layer} ({best_acc:.1%} accuracy on 20-way classification, {probe['layers'][best_layer]['probe_accuracy_factor_over_chance']:.1f}× chance)")

    if arousal and arousal["layers"]:
        best_v_layer = max(arousal["layers"].keys(), key=lambda lk: arousal["layers"][lk]["valence_separation"])
        ld = arousal["layers"][best_v_layer]
        lines.append(f"- **Best valence layer**: {best_v_layer} (PC{ld['best_valence_pc']} separation = {ld['valence_separation']:.2f})")
        lines.append(f"- **Best arousal axis**: PC{ld['best_arousal_pc']} (separation = {ld['arousal_separation']:.2f})")

    if implicit:
        lines.append(f"- **Implicit-emotion top-3 accuracy**: {implicit['top3_accuracy']:.0%} (chance: 15%)")

    out_path = model_dir / "REPORT.md"
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"Saved → {out_path}")


if __name__ == "__main__":
    main()
